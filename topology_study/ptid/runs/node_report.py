"""All tables of the node MIQP tests, rebuilt from the saved rows into experiments/node_miqp/TABLES.md.

Run from topology_study:  python -m ptid.runs.node_report
"""
from __future__ import annotations

import argparse
import contextlib
import io
from pathlib import Path

from ptid.runs import (node_confirm, node_exact, node_pipeline, node_price, node_probe, node_probe_roots, node_recovery, node_roots,
                       node_roots_e2e)

HERE = Path(__file__).resolve().parents[2]/"experiments"/"node_miqp"
PARTS = (("N1 exactness and scaling", node_exact, "exact.jsonl"),
         ("N2 recovery of hidden lines", node_recovery, "recovery.jsonl"),
         ("N2b the price of a line found among many (post hoc)", node_price, "recovery.jsonl"),
         ("N3 Algorithm 1 end to end", node_pipeline, "pipeline.jsonl"),
         ("N4 probing an open node question", node_probe, "probe.jsonl"),
         ("N5 root lines", node_roots, "roots.jsonl"),
         ("N7 version 1: root lines end to end, the draft's Algorithm 1", node_roots_e2e, "roots_e2e_v1.jsonl"),
         ("N7 version 2: root lines end to end with the line swap", node_roots_e2e, "roots_e2e.jsonl"),
         ("N6 probing an open root line", node_probe_roots, "probe_roots.jsonl"),
         ("N8 confirmation of the frozen method", node_confirm, "confirm.jsonl"))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", default=str(HERE/"TABLES.md"))
    args = p.parse_args()
    text = ["# Node MIQP tests: tables rebuilt from the saved rows\n",
            "Generated by `python -m ptid.runs.node_report`; see README.md for the design.\n"]
    for title, module, rows in PARTS:
        path = HERE/rows
        text.append(f"\n## {title}\n")
        if not path.exists():
            text.append(f"No rows yet ({rows}).\n")
            continue
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            module.summary(argparse.Namespace(out=str(path), exact=str(HERE/"exact.jsonl")))
        text.append(buffer.getvalue().replace(str(path), rows))
    Path(args.out).write_text("\n".join(text), encoding="utf-8")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
