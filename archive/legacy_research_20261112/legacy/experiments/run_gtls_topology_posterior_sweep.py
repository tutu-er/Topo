METHOD_COLUMNS = {
    "fixed_ols_rnj": "fixed_ols_f1",
    "fixed_gtls_rnj": "fixed_gtls_f1",
    "ols_candidate_eiv": "ols_candidate_f1",
    "gtls_candidate_eiv": "gtls_candidate_f1",
    "union_gtls_posterior": "gtls_posterior_f1",
    "gtls_clade_consensus": "gtls_consensus_f1",
    "ac_bic": "ac_bic_f1",
    "ac_quartet": "ac_quartet_f1",
}


def _relative_matrix_error(estimate: np.ndarray, truth: np.ndarray) -> float:
    """Return relative Frobenius error."""

    return float(
        np.linalg.norm(estimate - truth, ord="fro") / max(np.linalg.norm(truth, ord="fro"), 1e-15)
    )


def _source_scores(
    posterior: GTLSTopologyPosterior,
    source: str,
) -> list:
    """Return ranked scores whose candidate was generated by one estimator."""

    return [score for score in posterior.ranked if source in score.projection.sources]


def _evaluate(
    condition_id: str,
    case: str,
    data_regime: str,
    noise_regime: str,
    trial: int,
    quartet_replicates: int,
    gtls_shrinkage: float,
    temporal_block_length: int,
    posterior_temperature: float,
    complexity_weight: float,
    matrix_weight: float,
) -> tuple[dict, list[dict]]:
    """Evaluate one AC-generated noisy condition."""

    data = DATA_REGIMES[data_regime]
    noise = NOISE_REGIMES[noise_regime]
    started = time.perf_counter()
    net, scenarios = _build_scenarios(
        case,
        data["scenario_count"],
        data["sample_count"],
        noise["pq_noise_rel"],
        noise["v_noise_rel"],
        trial,
    )
    terminals = [int(column) for column in scenarios[0]["P_terminal"].columns]
    truth = set(rooted_clades(net.closed_edges(), net.root_bus, terminals))
    validation_count = representative_validation_count(data["scenario_count"])
    training = scenarios[:-validation_count]
    ols_r, ols_x, ols_r2, condition_number = fit_projected_sensitivity(
        training,
        constraint_mode="ordered",
    )
    fixed_ols = generate_rnj_candidates(
        ols_r,
        ols_x,
        terminals,
        net.root_bus,
        distance_modes=("RX_75R_25X",),
        tolerance_factors=(0.24,),
    )[0]
    posterior = infer_gtls_topology_posterior(
        scenarios,
        root_bus=net.root_bus,
        pq_noise_relative_std=noise["pq_noise_rel"],
        voltage_noise_relative_std=noise["v_noise_rel"],
        validation_scenario_count=validation_count,
        shrinkage_to_ols=gtls_shrinkage,
        temporal_block_length=temporal_block_length,
        posterior_temperature=posterior_temperature,
        complexity_weight=complexity_weight,
        matrix_weight=matrix_weight,
    )
    fixed_gtls = generate_rnj_candidates(
        posterior.estimate.r_matrix,
        posterior.estimate.x_matrix,
        terminals,
        net.root_bus,
        distance_modes=("RX_75R_25X",),
        tolerance_factors=(0.24,),
    )[0]
    ols_source = _source_scores(posterior, "ols")
    gtls_source = _source_scores(posterior, "gtls")
    if not ols_source or not gtls_source:
        raise RuntimeError("both OLS and GTLS candidate sources must be nonempty")
    ac_result = select_and_validate_topology(
        scenarios,
        net,
        pq_noise_relative_std=noise["pq_noise_rel"],
        voltage_noise_relative_std=noise["v_noise_rel"],
        bic_complexity_weight=1.0,
        quartet_replicates=quartet_replicates,
        quartet_confidence=0.90,
        quartet_positive_support=0.80,
        quartet_minimum_effect=0.002,
        minimum_edge_strength_ratio=0.02,
        quartet_contradiction_effect=0.05,
        validation_scenario_count=validation_count,
        seed=20260714 + 1000 * trial + 37 * len(case),
    )
    predictions = {
        "fixed_ols": set(fixed_ols.clades),
        "fixed_gtls": set(fixed_gtls.clades),
        "ols_candidate": set(ols_source[0].projection.candidate.clades),
        "gtls_candidate": set(gtls_source[0].projection.candidate.clades),
        "gtls_posterior": set(posterior.selected.projection.candidate.clades),
        "gtls_consensus": set(posterior.consensus_clades),
        "ac_bic": set(ac_result.raw_clades),
        "ac_quartet": set(ac_result.validated_clades),
    }
    metrics = {name: _metrics(value, truth) for name, value in predictions.items()}
    true_r, true_x = build_reduced_sensitivity_matrices(
        net,
        observed_terminals=terminals,
        injection_terminals=terminals,
        voltage_model="squared-voltage",
    )
    exact_probability = sum(
        score.posterior_probability
        for score in posterior.ranked
        if set(score.projection.candidate.clades) == truth
    )
    source_diagnostics = {}
    for source, scores in (("ols", ols_source), ("gtls", gtls_source)):
        source_metrics = [
            _metrics(set(score.projection.candidate.clades), truth) for score in scores
        ]
        source_diagnostics[f"{source}_candidate_count"] = len(scores)
        source_diagnostics[f"{source}_candidate_oracle_f1"] = max(
            float(item["f1"]) for item in source_metrics
        )
        source_diagnostics[f"{source}_candidate_exact_coverage"] = any(
            bool(item["exact"]) for item in source_metrics
        )
    row = {
        "condition_id": condition_id,
        "status": "ok",
        "case": case,
        "data_regime": data_regime,
        "noise_regime": noise_regime,
        "trial": trial,
        "scenario_count": data["scenario_count"],
        "sample_count": data["sample_count"],
        "training_scenario_count": len(training),
        "validation_scenario_count": validation_count,
        "pq_noise_rel": noise["pq_noise_rel"],
        "v_noise_rel": noise["v_noise_rel"],
        "terminal_count": len(terminals),
        "truth_clade_count": len(truth),
        "ols_r2": ols_r2,
        "ols_condition_number": condition_number,
        "gtls_r2": posterior.estimate.r2_score,
        "gtls_augmented_condition_number": (posterior.estimate.augmented_condition_number),
        "gtls_response_subspace_condition_number": (
            posterior.estimate.response_subspace_condition_number
        ),
        "gtls_correction_ratio": posterior.estimate.correction_ratio,
        "ols_relative_error_r": _relative_matrix_error(ols_r, true_r),
        "ols_relative_error_x": _relative_matrix_error(ols_x, true_x),
        "gtls_relative_error_r": _relative_matrix_error(
            posterior.estimate.r_matrix,
            true_r,
        ),
        "gtls_relative_error_x": _relative_matrix_error(
            posterior.estimate.x_matrix,
            true_x,
        ),
        "posterior_candidate_count": posterior.candidate_count,
        "posterior_effective_observation_count": (posterior.effective_observation_count),
        "posterior_map_probability": (posterior.selected.posterior_probability),
        "posterior_true_probability": exact_probability,
        "posterior_entropy": posterior.posterior_entropy,
        "posterior_effective_candidate_count": posterior.effective_candidate_count,
        "posterior_top_two_probability_gap": posterior.top_two_probability_gap,
        "posterior_selected_sources": "+".join(sorted(posterior.selected.projection.sources)),
        "posterior_selected_mode": (posterior.selected.projection.candidate.distance_mode),
        "posterior_selected_tolerance": (posterior.selected.projection.candidate.tolerance_factor),
        "posterior_predictive_nll": (posterior.selected.predictive_negative_log_likelihood),
        "posterior_complexity_penalty": (posterior.selected.complexity_penalty),
        "posterior_matrix_penalty": posterior.selected.matrix_penalty,
        "elapsed_seconds": time.perf_counter() - started,
        "error": "",
        **source_diagnostics,
    }
    for name, values in metrics.items():
        for metric, value in values.items():
            row[f"{name}_{metric}"] = value
    candidate_rows = []
    for rank, score in enumerate(posterior.ranked, start=1):
        candidate_metrics = _metrics(
            set(score.projection.candidate.clades),
            truth,
        )
        candidate_rows.append(
            {
                "condition_id": condition_id,
                "case": case,
                "data_regime": data_regime,
                "noise_regime": noise_regime,
                "trial": trial,
                "rank": rank,
                "sources": "+".join(sorted(score.projection.sources)),
                "distance_mode": score.projection.candidate.distance_mode,
                "tolerance_factor": score.projection.candidate.tolerance_factor,
                "hidden_clade_count": len(score.projection.candidate.clades),
                "relative_matrix_error": score.projection.relative_matrix_error,
                "predictive_nll": score.predictive_negative_log_likelihood,
                "complexity_penalty": score.complexity_penalty,
                "matrix_penalty": score.matrix_penalty,
                "selection_loss": score.selection_loss,
                "posterior_probability": score.posterior_probability,
                **candidate_metrics,
            }
        )
    return row, candidate_rows


def _long_frame(frame: pd.DataFrame) -> pd.DataFrame:
    """Convert wide condition metrics to method-level records."""

    records = []
    for _, row in frame.iterrows():
        for method, column in METHOD_COLUMNS.items():
            records.append(
                {
                    "condition_id": row["condition_id"],
                    "case": row["case"],
                    "data_regime": row["data_regime"],
                    "noise_regime": row["noise_regime"],
                    "trial": row["trial"],
                    "method": method,
                    "f1": row[column],
                    "exact": row[column.replace("_f1", "_exact")],
                }
            )
    return pd.DataFrame(records)


def _write_report(output: Path, frame: pd.DataFrame, long: pd.DataFrame) -> None:
    """Write a compact evidence report."""

    overall = (
        long.groupby("method", as_index=False)
        .agg(
            mean_f1=("f1", "mean"),
            min_f1=("f1", "min"),
            exact_rate=("exact", "mean"),
        )
        .sort_values("mean_f1", ascending=False)
    )
    by_case = long.groupby(["case", "method"], as_index=False).agg(
        mean_f1=("f1", "mean"), exact_rate=("exact", "mean")
    )
    lines = [
        "# GTLS topology posterior sweep",
        "",
        "All P/Q/V observations are noisy and generated from radial AC power flow.",
        "The reported topology probabilities are a tempered generalized posterior",
        "over the finite OLS/GTLS RNJ candidate union, not an exact full Bayesian posterior.",
        "",
        "## Overall",
        "",
        "| method | mean F1 | minimum F1 | exact rate |",
        "|---|---:|---:|---:|",
    ]
    for _, row in overall.iterrows():
        lines.append(
            f"| {row['method']} | {row['mean_f1']:.4f} | "
            f"{row['min_f1']:.4f} | {row['exact_rate']:.2%} |"
        )
    lines.extend(
        [
            "",
            "## By case",
            "",
            "| case | method | mean F1 | exact rate |",
            "|---|---|---:|---:|",
        ]
    )
    for _, row in by_case.iterrows():
        lines.append(
            f"| {row['case']} | {row['method']} | {row['mean_f1']:.4f} | {row['exact_rate']:.2%} |"
        )
    lines.extend(
        [
            "",
            "## GTLS diagnostics",
            "",
            f"- Mean OLS R/X relative error: {frame['ols_relative_error_r'].mean():.4f} / "
            f"{frame['ols_relative_error_x'].mean():.4f}",
            f"- Mean GTLS R/X relative error: {frame['gtls_relative_error_r'].mean():.4f} / "
            f"{frame['gtls_relative_error_x'].mean():.4f}",
            f"- Exact topology in OLS candidate sets: "
            f"{frame['ols_candidate_exact_coverage'].mean():.2%}",
            f"- Exact topology in GTLS candidate sets: "
            f"{frame['gtls_candidate_exact_coverage'].mean():.2%}",
            f"- Mean MAP posterior mass: {frame['posterior_map_probability'].mean():.4f}",
            f"- Mean true-topology posterior mass: "
            f"{frame['posterior_true_probability'].mean():.4f}",
            f"- Mean effective candidate count: "
            f"{frame['posterior_effective_candidate_count'].mean():.2f}",
        ]
    )
    (output / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _persist(output: Path, rows: list[dict], candidate_rows: list[dict]) -> None:
    """Persist resumable condition and candidate tables."""

    frame = pd.DataFrame(rows)
    if not frame.empty:
        frame = frame.sort_values("condition_id")
    frame.to_csv(output / "metrics.csv", index=False)
    pd.DataFrame(candidate_rows).to_csv(output / "candidate_posterior.csv", index=False)


def run(args: argparse.Namespace) -> None:
    """Run the requested GTLS posterior sweep."""

    output = ensure_dir(args.output)
    metrics_path = output / "metrics.csv"
    candidates_path = output / "candidate_posterior.csv"
    rows = (
        pd.read_csv(metrics_path).to_dict("records")
        if args.resume and metrics_path.exists()
        else []
    )
    candidate_rows = (
        pd.read_csv(candidates_path).to_dict("records")
        if args.resume and candidates_path.exists()
        else []
    )
    completed = {str(row["condition_id"]) for row in rows if str(row.get("status", "")) == "ok"}
    conditions = [
        (case, data_regime, noise_regime, trial)
        for case in args.cases
        for data_regime in args.data_regimes
        for noise_regime in args.noise_regimes
        for trial in range(args.trial_offset, args.trial_offset + args.trials)
    ]
    total = len(conditions)
    started = time.perf_counter()
    processed = 0
    for index, (case, data_regime, noise_regime, trial) in enumerate(
        conditions,
        start=1,
    ):
        condition_id = f"{case}__{data_regime}__{noise_regime}__trial{trial}"
        if condition_id in completed:
            print(f"[{index:03d}/{total:03d}] skip {condition_id}", flush=True)
            continue
        print(f"[{index:03d}/{total:03d}] run  {condition_id}", flush=True)
        try:
            row, candidates = _evaluate(
                condition_id,
                case,
                data_regime,
                noise_regime,
                trial,
                args.quartet_replicates,
                args.gtls_shrinkage,
                args.temporal_block_length,
                args.posterior_temperature,
                args.complexity_weight,
                args.matrix_weight,
            )
            rows.append(row)
            candidate_rows.extend(candidates)
            print(
                f"    fixed_ols={row['fixed_ols_f1']:.4f} "
                f"fixed_gtls={row['fixed_gtls_f1']:.4f} "
                f"gtls_post={row['gtls_posterior_f1']:.4f} "
                f"ac_quartet={row['ac_quartet_f1']:.4f}",
                flush=True,
            )
        except Exception as error:
            rows.append(
                {
                    "condition_id": condition_id,
                    "status": "error",
                    "case": case,
                    "data_regime": data_regime,
                    "noise_regime": noise_regime,
                    "trial": trial,
                    "error": repr(error),
                }
            )
            print(f"    ERROR: {error!r}", flush=True)
        processed += 1
        _persist(output, rows, candidate_rows)
        elapsed = time.perf_counter() - started
        eta = elapsed / processed * max(total - index, 0) if processed else 0.0
        print(f"    elapsed={elapsed:.1f}s eta={eta:.1f}s", flush=True)

    frame = pd.DataFrame(rows)
    frame = frame.loc[frame["status"].eq("ok")].copy()
    if frame.empty:
        raise RuntimeError("no GTLS posterior conditions completed successfully")
    long = _long_frame(frame)
    long.to_csv(output / "method_metrics_long.csv", index=False)
    (
        long.groupby("method", as_index=False)
        .agg(
            mean_f1=("f1", "mean"),
            min_f1=("f1", "min"),
            exact_rate=("exact", "mean"),
        )
        .sort_values("mean_f1", ascending=False)
        .to_csv(output / "summary_by_method.csv", index=False)
    )
    (
        long.groupby(["case", "method"], as_index=False)
        .agg(mean_f1=("f1", "mean"), exact_rate=("exact", "mean"))
        .to_csv(output / "summary_by_case.csv", index=False)
    )
    (
        long.groupby(["data_regime", "noise_regime", "method"], as_index=False)
        .agg(
            mean_f1=("f1", "mean"),
            min_f1=("f1", "min"),
            exact_rate=("exact", "mean"),
        )
        .to_csv(output / "summary_by_regime.csv", index=False)
    )
    write_json(
        output / "summary.json",
        {
            "completed_conditions": len(frame),
            "requested_conditions": total,
            "cases": args.cases,
            "data_regimes": args.data_regimes,
            "noise_regimes": args.noise_regimes,
            "trials": args.trials,
            "trial_offset": args.trial_offset,
            "gtls_shrinkage": args.gtls_shrinkage,
            "temporal_block_length": args.temporal_block_length,
            "posterior_temperature": args.posterior_temperature,
            "complexity_weight": args.complexity_weight,
            "matrix_weight": args.matrix_weight,
            "all_measurements_noisy": True,
            "voltage_generation": "radial_ac_power_flow",
            "posterior_interpretation": "tempered_generalized_finite_candidate",
        },
    )
    _write_report(output, frame, long)


def main() -> None:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="outputs/gtls_topology_posterior_sweep")
    parser.add_argument(
        "--cases",
        nargs="+",
        choices=sorted(CASE_BUILDERS),
        default=["paper15", "soumalas11", "flynn16", "pengwah18"],
    )
    parser.add_argument(
        "--data-regimes",
        nargs="+",
        choices=sorted(DATA_REGIMES),
        default=["sparse", "medium", "rich"],
    )
    parser.add_argument(
        "--noise-regimes",
        nargs="+",
        choices=sorted(NOISE_REGIMES),
        default=["low", "nominal", "high"],
    )
    parser.add_argument("--trials", type=int, default=1)
    parser.add_argument("--trial-offset", type=int, default=0)
    parser.add_argument("--quartet-replicates", type=int, default=12)
    parser.add_argument("--gtls-shrinkage", type=float, default=0.99)
    parser.add_argument("--temporal-block-length", type=int, default=12)
    parser.add_argument("--posterior-temperature", type=float, default=1.0)
    parser.add_argument("--complexity-weight", type=float, default=0.25)
    parser.add_argument("--matrix-weight", type=float, default=0.0)
    parser.add_argument("--resume", action="store_true")
    args = parser.parse_args()
    if args.trials <= 0:
        parser.error("--trials must be positive")
    if args.quartet_replicates <= 0:
        parser.error("--quartet-replicates must be positive")
    if not 0.0 <= args.gtls_shrinkage <= 1.0:
        parser.error("--gtls-shrinkage must be in [0, 1]")
    run(args)


if __name__ == "__main__":
    main()
